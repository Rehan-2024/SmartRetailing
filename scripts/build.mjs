import {mkdir,cp,readFile,rm} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {build} from 'esbuild';
const data=JSON.parse(await readFile('public/data/report.json','utf8'));
if(!data.retail || !data.purchase || !data.forecast) throw Error('Run python pipeline/train.py --data-root .. before building');
const market=JSON.parse(await readFile('public/data/market.json','utf8'));
if(!market.demand||!market.coldStart)throw Error('Run python pipeline/build_market.py --data-root ..');
await mkdir('public/vendor',{recursive:true});
await build({entryPoints:['read-excel-file/universal'],bundle:true,platform:'browser',format:'esm',outfile:'public/vendor/excel-reader.js',minify:true});
const root=resolve(import.meta.dirname,'..');
const output=resolve(root,'dist');
if(dirname(output)!==root||resolve(process.cwd())!==root)throw Error('Build must run at the repository root');
await rm(output,{recursive:true,force:true});
await mkdir(output,{recursive:true});
await cp('public','dist',{recursive:true});
console.log('Built product-market tool with '+market.products.length+' merchandise products.');
